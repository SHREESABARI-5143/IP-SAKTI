/**
 * Translation helper function.
 * @param {string} lang - Language code ('en', 'hi', 'sa', 'ta', 'te', 'mr', 'bn')
 * @param {string} key - Translation key
 * @param {object} params - Optional parameters to interpolate (e.g. { step: 1 })
 * @returns {string} Translated string or fallback to English
 */
export function t(lang, key, params = {}) {
  const currentLang = translations[lang] || translations.en;
  let text = currentLang[key] || translations.en[key] || key;

  if (typeof text === "string" && params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    });
  }

  return text;
}
